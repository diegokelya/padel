#!/usr/bin/env python3
"""Builds copy/<language>.js, the text of the landing page in the languages that are not Spanish or English, one small
file each so that a visitor only downloads the one they read.

`scripts/i18n/keys.json` lists the keys of the English copy in `app.js` (the numbering), and each
`scripts/i18n/<language>.txt` has one line per key: `<number> <text>`. The keys that are not texts (`switchTo`,
`switchLabel`, `supportUrl`, `privacyUrl`) are filled in here.

Usage: python3 scripts/build-copy.py          # write copy.extra.js
       python3 scripts/build-copy.py --check  # fail if a text is missing or the file is stale
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ['it', 'pt', 'de', 'fr', 'sv', 'nl']
SKIPPED = {'switchTo', 'switchLabel', 'supportUrl', 'privacyUrl'}


def js(value):
    return json.dumps(value, ensure_ascii=False)


def build():
    keys = json.load(open(os.path.join(ROOT, 'scripts/i18n/keys.json'), encoding='utf-8'))
    problems, languages = [], {}
    for code in LANGS:
        lines = {}
        for line in open(os.path.join(ROOT, f'scripts/i18n/{code}.txt'), encoding='utf-8').read().split('\n'):
            if line.strip():
                number, _, text = line.partition(' ')
                lines[int(number)] = text
        entry = {}
        for index, key in enumerate(keys):
            if key in SKIPPED:
                continue
            if index not in lines:
                problems.append(f'{code}: "{key}" (line {index}) is missing')
            else:
                entry[key] = lines[index]
        entry['supportUrl'] = f'support/{code}.html'
        entry['privacyUrl'] = f'privacy/{code}.html'
        languages[code] = entry
    files = {}
    for code, entry in languages.items():
        body = ',\n'.join(f'  {k}: {js(v)}' for k, v in entry.items())
        files[code] = ('// Generated by scripts/build-copy.py from scripts/i18n/' + code + '.txt. Do not edit by hand.\n'
                       f'(window.extraCopy = window.extraCopy || {{}}).{code} = {{\n{body}\n}};\n')
    return files, problems


if __name__ == '__main__':
    files, problems = build()
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        sys.exit(1)
    folder = os.path.join(ROOT, 'copy')
    os.makedirs(folder, exist_ok=True)
    stale = [c for c, text in files.items() if not os.path.exists(os.path.join(folder, f'{c}.js'))
             or open(os.path.join(folder, f'{c}.js'), encoding='utf-8').read() != text]
    if '--check' in sys.argv:
        if stale:
            print('Out of date (run python3 scripts/build-copy.py):', *[f'copy/{c}.js' for c in stale], sep='\n  ', file=sys.stderr)
            sys.exit(1)
        print('Copy OK.')
    else:
        for code, text in files.items():
            open(os.path.join(folder, f'{code}.js'), 'w', encoding='utf-8').write(text)
            print('wrote', f'copy/{code}.js')
